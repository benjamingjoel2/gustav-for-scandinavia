/**
 * Builds the static SVG map of Scandinavia and Finland used by the route builder.
 * Source: Natural Earth 1:50m via the world-atlas package (public domain).
 * Run: npx tsx scripts/build-map.ts
 */
import { writeFileSync } from "node:fs";
import { geoConicConformal, geoPath, type GeoProjection } from "d3-geo";
import { feature } from "topojson-client";
import type { Feature, FeatureCollection, MultiPolygon, Polygon, Position } from "geojson";
import type { Topology } from "topojson-specification";
import world from "world-atlas/countries-50m.json" with { type: "json" };
import { places } from "../data/places";

type CountryFeature = Feature<Polygon | MultiPolygon, { name: string }>;

const W = 1000;
const NORDIC: Record<string, string> = { "578": "norway", "752": "sweden", "208": "denmark", "246": "finland", "234": "denmark", "248": "finland" };
const NEIGHBOURS = new Set(["643", "233", "428", "440", "616", "276", "352", "826", "528", "112", "804"]);

const all = (feature(world as unknown as Topology, (world as unknown as Topology).objects.countries) as FeatureCollection<Polygon | MultiPolygon, { name: string }>).features as CountryFeature[];

const polygons = (f: CountryFeature): Position[][][] => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates);
const maxLat = (poly: Position[][]) => Math.max(...poly[0].map((p) => p[1]));
const minLng = (poly: Position[][]) => Math.min(...poly[0].map((p) => p[0]));

// Split Norway: mainland (+ coastal islands) vs Svalbard (drawn in an inset). Drop Jan Mayen.
const mainland: CountryFeature[] = [];
const svalbard: Position[][][] = [];
for (const f of all) {
  const id = String(f.id);
  if (!NORDIC[id]) continue;
  const keep: Position[][][] = [];
  for (const poly of polygons(f)) {
    if (id === "578" && maxLat(poly) > 74) svalbard.push(poly);
    else if (id === "578" && minLng(poly) < -5) continue; // Jan Mayen
    else keep.push(poly);
  }
  mainland.push({ ...f, geometry: { type: "MultiPolygon", coordinates: keep } });
}

const projection: GeoProjection = geoConicConformal().parallels([58, 68]).rotate([-14, 0]);
projection.fitWidth(W - 40, { type: "FeatureCollection", features: mainland });
projection.translate([projection.translate()[0] + 20, projection.translate()[1] + 20]);
const bounds = geoPath(projection).bounds({ type: "FeatureCollection", features: mainland });
const H = Math.ceil(bounds[1][1] + 20);
projection.clipExtent([
  [0, 0],
  [W, H],
]);

const svalbardFeature: Feature<MultiPolygon> = { type: "Feature", properties: {}, geometry: { type: "MultiPolygon", coordinates: svalbard } };
const INSET = { x: 24, y: 24, w: 230, h: 200 };
const insetProjection = geoConicConformal().parallels([77, 80]).rotate([-18, 0]).fitExtent(
  [
    [INSET.x + 12, INSET.y + 12],
    [INSET.x + INSET.w - 12, INSET.y + INSET.h - 12],
  ],
  svalbardFeature,
);

const round = (d: string | null) => (d ?? "").replace(/(\d+\.\d)\d+/g, "$1");
const path = geoPath(projection);

const countries = mainland.map((f) => ({ country: NORDIC[String(f.id)], d: round(path(f)) }));
const neighbours = all.filter((f) => NEIGHBOURS.has(String(f.id))).map((f) => round(path(f))).filter(Boolean);
const svalbardPath = round(geoPath(insetProjection)(svalbardFeature));

const points = Object.fromEntries(
  places.map((p) => {
    const [x, y] = (p.id === "svalbard" ? insetProjection : projection)([p.lng, p.lat])!;
    return [p.id, { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }];
  }),
);

const out = `// Generated by scripts/build-map.ts from Natural Earth 1:50m (public domain). Do not edit by hand.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
export const SVALBARD_INSET = ${JSON.stringify(INSET)};
export const countryPaths: { country: "norway" | "sweden" | "denmark" | "finland"; d: string }[] = ${JSON.stringify(countries)};
export const neighbourPaths: string[] = ${JSON.stringify(neighbours)};
export const svalbardPath = ${JSON.stringify(svalbardPath)};
export const mapPoints: Record<string, { x: number; y: number }> = ${JSON.stringify(points)};
`;
writeFileSync(new URL("../components/route/map-data.ts", import.meta.url), out);
console.log(`map ${W}x${H}, ${(out.length / 1024).toFixed(0)} KB`);
